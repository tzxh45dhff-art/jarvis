"""
Clipboard history: everything the user copies (text only), searchable later -
"the link I copied this morning".

Kept on this Mac, the last 300 items or 30 days. Anything a password manager
or other app marks as secret (the nspasteboard.org "concealed" and "transient"
markers, which 1Password, Bitwarden, Keychain and others set) is never stored,
and neither is anything that looks like a password, card number or one-time
code.
"""
from __future__ import annotations

import logging
import os
import re
import sqlite3
import threading
import time
from pathlib import Path

from ..config import DATA_DIR

log = logging.getLogger("jarvis.clips")

DB = Path(os.environ.get("JARVIS_CLIPS_DB") or DATA_DIR / "clips.sqlite3")
KEEP = 300
KEEP_DAYS = 30
_SKIP_TYPES = ("org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
               "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
               "com.bitwarden.desktop")
_SECRETISH = re.compile(
    r"^\s*(\d{4,8}|\d{4}[ -]?\d{4}[ -]?\d{4}[ -]?\d{4}|sk-[A-Za-z0-9]{20,}|"
    r"(?=\S*[A-Z])(?=\S*[a-z])(?=\S*\d)(?=\S*[^\w\s])\S{10,40})\s*$")
_LOCK = threading.Lock()


def _conn() -> sqlite3.Connection:
    DB.parent.mkdir(parents=True, exist_ok=True)
    c = sqlite3.connect(DB, timeout=10, check_same_thread=False)
    c.execute("CREATE TABLE IF NOT EXISTS clips (id INTEGER PRIMARY KEY, ts REAL, "
              "text TEXT NOT NULL, app TEXT NOT NULL DEFAULT '')")
    return c


def add(text: str, app: str = "") -> bool:
    t = (text or "").strip()
    if not t or len(t) > 20000 or _SECRETISH.match(t):
        return False
    with _LOCK, _conn() as c:
        last = c.execute("SELECT text FROM clips ORDER BY id DESC LIMIT 1").fetchone()
        if last and last[0] == t:
            return False
        c.execute("INSERT INTO clips(ts, text, app) VALUES(?,?,?)", (time.time(), t, app or ""))
        c.execute("DELETE FROM clips WHERE id NOT IN (SELECT id FROM clips ORDER BY id DESC LIMIT ?) "
                  "OR ts < ?", (KEEP, time.time() - KEEP_DAYS * 86400))
    return True


def search(query: str = "", limit: int = 10) -> list[dict]:
    q = (query or "").strip().lower()
    with _LOCK, _conn() as c:
        rows = c.execute("SELECT id, ts, text, app FROM clips ORDER BY id DESC LIMIT ?",
                         (KEEP,)).fetchall()
    out = []
    words = [w for w in re.findall(r"\w+", q) if len(w) > 1]
    kind = None
    if re.search(r"\b(link|url|website)\b", q):
        kind = "link"
    elif re.search(r"\b(email|mail address)\b", q):
        kind = "email"
    elif re.search(r"\b(phone|number)\b", q):
        kind = "phone"
    for cid, ts, text, app in rows:
        low = text.lower()
        if kind == "link" and not re.search(r"https?://|www\.", low):
            continue
        if kind == "email" and "@" not in low:
            continue
        if kind == "phone" and ("://" in low or not re.search(r"(?<![\w/])\+?\d[\d \-]{7,}\d\b", low)):
            continue
        content_words = [w for w in words if w not in ("link", "url", "website", "email",
                                                       "phone", "number", "copied", "the", "that", "i")]
        if content_words and not all(w in low or w in app.lower() for w in content_words):
            continue
        out.append({"id": cid, "text": text[:2000], "app": app,
                    "copied": _ago(ts)})
        if len(out) >= limit:
            break
    return out


def get(cid: int) -> str:
    with _LOCK, _conn() as c:
        row = c.execute("SELECT text FROM clips WHERE id=?", (int(cid),)).fetchone()
    return row[0] if row else ""


def clear() -> int:
    with _LOCK, _conn() as c:
        return c.execute("DELETE FROM clips").rowcount


def _ago(ts: float) -> str:
    s = time.time() - ts
    if s < 90:
        return "just now"
    if s < 3600:
        return f"{int(s // 60)} min ago"
    if s < 86400:
        return f"{int(s // 3600)} h ago"
    return time.strftime("%a %d %b %H:%M", time.localtime(ts))


class ClipWatcher:
    """Polls the pasteboard's change counter once a second (cheap: one int)."""

    def __init__(self, every: float = 1.0):
        self.every = every
        self._stop = threading.Event()
        self._count = None

    def start(self) -> None:
        threading.Thread(target=self._loop, daemon=True, name="clip-watch").start()

    def stop(self) -> None:
        self._stop.set()

    def _loop(self) -> None:
        try:
            from AppKit import NSPasteboard, NSPasteboardTypeString
        except Exception as e:                                # noqa: BLE001
            log.info("clipboard history unavailable: %s", e)
            return
        pb = NSPasteboard.generalPasteboard()
        self._count = pb.changeCount()
        while not self._stop.wait(self.every):
            try:
                n = pb.changeCount()
                if n == self._count:
                    continue
                self._count = n
                from .profile import _setting
                if _setting("clipboard", "on") != "on":
                    continue
                types = [str(t) for t in (pb.types() or [])]
                if any(t in _SKIP_TYPES for t in types):
                    continue
                text = pb.stringForType_(NSPasteboardTypeString)
                if text:
                    app = ""
                    try:
                        from ..context import front_window
                        app = front_window()[0]
                    except Exception:
                        pass
                    add(str(text), app)
            except Exception as e:                            # noqa: BLE001
                log.debug("clip tick failed: %s", e)
